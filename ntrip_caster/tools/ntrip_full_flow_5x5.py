class RtcmReceiveParser:
    """Incrementally extract and CRC-check RTCM3 frames from TCP."""

    def __init__(self) -> None:
        self.buffer = bytearray()

    def reset(self) -> None:
        self.buffer.clear()

    def feed(self, data: bytes) -> tuple[list[bytes], int]:
        self.buffer.extend(data)
        frames: list[bytes] = []
        crc_errors = 0

        while True:
            if len(self.buffer) < 3:
                break

            if self.buffer[0] != 0xD3:
                try:
                    preamble_index = self.buffer.index(0xD3)
                    del self.buffer[:preamble_index]
                except ValueError:
                    self.buffer.clear()
                    break

            if len(self.buffer) < 3:
                break

            if self.buffer[1] & 0xFC:
                del self.buffer[0]
                continue

            payload_length = ((self.buffer[1] & 0x03) << 8) | self.buffer[2]
            frame_length = 3 + payload_length + 3

            if len(self.buffer) < frame_length:
                break

            frame = bytes(self.buffer[:frame_length])

            if validate_rtcm_frame(frame):
                frames.append(frame)
                del self.buffer[:frame_length]
                continue

            crc_errors += 1
            # Match the hardware parser's resynchronisation strategy: discard
            # the bad preamble and scan for the next D3 byte.
            del self.buffer[0]

        return frames, crc_errors


def _nmea_coordinate(value: float, latitude: bool) -> tuple[str, str]:
    absolute = abs(value)
    degrees = int(absolute)
    minutes = (absolute - degrees) * 60.0

    # ntrip.cc rounds to exactly four decimal places and handles minute carry.
    rounded_minutes = round(minutes, 4)
    if rounded_minutes >= 60.0:
        rounded_minutes -= 60.0
        degrees += 1

    if latitude:
        coordinate = f"{degrees:02d}{rounded_minutes:07.4f}"
        hemisphere = "N" if value >= 0 else "S"
    else:
        coordinate = f"{degrees:03d}{rounded_minutes:07.4f}"
        hemisphere = "E" if value >= 0 else "W"

    return coordinate, hemisphere


def build_pi_bridge_gga(
    latitude: float,
    longitude: float,
    altitude_m: float,
    *,
    utc_time: time.struct_time | None = None,
) -> bytes:
    """Build the exact GGA shape generated by NTRIPBridge::makeGGA()."""
    utc = utc_time or time.gmtime()
    timestamp = f"{utc.tm_hour:02d}{utc.tm_min:02d}{utc.tm_sec:02d}"
    latitude_text, latitude_hemisphere = _nmea_coordinate(
        latitude, latitude=True
    )
    longitude_text, longitude_hemisphere = _nmea_coordinate(
        longitude, latitude=False
    )

    core = (
        f"GPGGA,{timestamp},"
        f"{latitude_text},{latitude_hemisphere},"
        f"{longitude_text},{longitude_hemisphere},"
        f"1,12,1.0,{altitude_m:.1f},M,0.0,M,,"
    )

    checksum = 0
    for byte in core.encode("ascii"):
        checksum ^= byte

    return f"${core}*{checksum:02X}\r\n".encode("ascii")


def build_pi_bridge_handshake(config: RoverConfig) -> bytes:
    """Build the exact HTTP request emitted by NTRIPClient::sendHttpHandshake."""
    request = (
        f"GET /{config.mountpoint} HTTP/1.0\r\n"
        f"Host: {config.ntrip_host}\r\n"
        "Ntrip-Version: Ntrip/2.0\r\n"
        f"User-Agent: {config.user_agent}\r\n"
    )

    if config.username or config.password:
        encoded = base64.b64encode(
            f"{config.username}:{config.password}".encode("utf-8")
        ).decode("ascii")
        request += f"Authorization: Basic {encoded}\r\n"

    return (request + "\r\n").encode("ascii")


def parse_rtcm_whitelist(value: str) -> frozenset[int]:
    ids: set[int] = set()
    for raw in value.split(","):
        token = raw.strip()
        if not token:
            continue
        message_id = int(token)
        if not 0 <= message_id <= 4095:
            raise ValueError(f"Invalid RTCM message ID: {message_id}")
        ids.add(message_id)
    return frozenset(ids)


def load_key_value_config(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for line_number, raw_line in enumerate(
        path.read_text(encoding="utf-8").splitlines(), start=1
    ):
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            raise ValueError(f"Malformed config line {line_number}: {line}")
        key, value = (part.strip() for part in line.split("=", 1))
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key] = value
    return values


def _config_bool(value: str | None, default: bool = False) -> bool:
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


def _optional_float(values: dict[str, str], key: str) -> float | None:
    value = values.get(key)
    if value is None or value.strip() == "":
        return None
    return float(value)


