# MAVLink 2 GPS_RTCM_DATA constants from common.xml/generated C headers.
MAVLINK2_MAGIC = 0xFD
MAVLINK_MSG_ID_GPS_RTCM_DATA = 233
MAVLINK_GPS_RTCM_DATA_PAYLOAD_LEN = 182
MAVLINK_GPS_RTCM_DATA_MAX_FIELD = 180
MAVLINK_GPS_RTCM_DATA_MAX_LOGICAL = 720
MAVLINK_GPS_RTCM_DATA_CRC_EXTRA = 35
MAVLINK_MSG_ID_GLOBAL_POSITION_INT = 33
MAVLINK_GLOBAL_POSITION_INT_PAYLOAD_LEN = 28
MAVLINK_GLOBAL_POSITION_INT_CRC_EXTRA = 104


def mavlink_x25_crc(data: bytes, crc_extra: int) -> int:
    crc = 0xFFFF

    def accumulate(byte: int, current: int) -> int:
        temporary = byte ^ (current & 0xFF)
        temporary ^= (temporary << 4) & 0xFF
        return (
            (current >> 8)
            ^ (temporary << 8)
            ^ (temporary << 3)
            ^ (temporary >> 4)
        ) & 0xFFFF

    for byte in data:
        crc = accumulate(byte, crc)
    return accumulate(crc_extra, crc)


def build_mavlink2_packet(
    *,
    payload: bytes,
    message_id: int,
    packet_sequence: int,
    system_id: int,
    component_id: int,
    crc_extra: int,
) -> bytes:
    if len(payload) > 255:
        raise ValueError("MAVLink payload exceeds 255 bytes.")

    header_without_magic = bytes(
        (
            len(payload),
            0,  # incompat flags
            0,  # compat flags
            packet_sequence & 0xFF,
            system_id & 0xFF,
            component_id & 0xFF,
        )
    ) + int(message_id).to_bytes(3, "little")

    checksum = mavlink_x25_crc(
        header_without_magic + payload,
        crc_extra,
    )

    return (
        bytes((MAVLINK2_MAGIC,))
        + header_without_magic
        + payload
        + checksum.to_bytes(2, "little")
    )


def validate_mavlink2_packet(packet: bytes, crc_extra: int) -> bool:
    if len(packet) < 12 or packet[0] != MAVLINK2_MAGIC:
        return False
    payload_length = packet[1]
    signature_length = 13 if packet[2] & 0x01 else 0
    expected_length = 10 + payload_length + 2 + signature_length
    if len(packet) != expected_length:
        return False
    checksum_end = len(packet) - signature_length
    received = int.from_bytes(packet[checksum_end - 2 : checksum_end], "little")
    computed = mavlink_x25_crc(packet[1 : 10 + payload_length], crc_extra)
    return received == computed


class MavlinkStreamParser:
    """Small MAVLink v1/v2 stream parser for GLOBAL_POSITION_INT."""

    def __init__(self) -> None:
        self.buffer = bytearray()

    def feed(self, data: bytes) -> list[bytes]:
        self.buffer.extend(data)
        packets: list[bytes] = []

        while self.buffer:
            try:
                v2_index = self.buffer.index(0xFD)
            except ValueError:
                v2_index = len(self.buffer)
            try:
                v1_index = self.buffer.index(0xFE)
            except ValueError:
                v1_index = len(self.buffer)

            start = min(v1_index, v2_index)
            if start == len(self.buffer):
                self.buffer.clear()
                break
            if start > 0:
                del self.buffer[:start]
            if len(self.buffer) < 2:
                break

            magic = self.buffer[0]
            payload_length = self.buffer[1]
            if magic == 0xFD:
                if len(self.buffer) < 10:
                    break
                signature_length = 13 if self.buffer[2] & 0x01 else 0
                packet_length = 10 + payload_length + 2 + signature_length
            else:
                if len(self.buffer) < 6:
                    break
                packet_length = 6 + payload_length + 2

            if len(self.buffer) < packet_length:
                break
            packets.append(bytes(self.buffer[:packet_length]))
            del self.buffer[:packet_length]

        return packets


def decode_global_position_int(packet: bytes) -> tuple[float, float, float] | None:
    if not packet:
        return None

    if packet[0] == 0xFD:
        payload_length = packet[1]
        message_id = int.from_bytes(packet[7:10], "little")
        payload_offset = 10
        signature_length = 13 if packet[2] & 0x01 else 0
        checksum_end = len(packet) - signature_length
        if message_id != MAVLINK_MSG_ID_GLOBAL_POSITION_INT:
            return None
        if payload_length < MAVLINK_GLOBAL_POSITION_INT_PAYLOAD_LEN:
            return None
        received = int.from_bytes(packet[checksum_end - 2 : checksum_end], "little")
        computed = mavlink_x25_crc(
            packet[1 : payload_offset + payload_length],
            MAVLINK_GLOBAL_POSITION_INT_CRC_EXTRA,
        )
        if received != computed:
            return None
    elif packet[0] == 0xFE:
        payload_length = packet[1]
        message_id = packet[5]
        payload_offset = 6
        if message_id != MAVLINK_MSG_ID_GLOBAL_POSITION_INT:
            return None
        if payload_length < MAVLINK_GLOBAL_POSITION_INT_PAYLOAD_LEN:
            return None
        received = int.from_bytes(packet[-2:], "little")
        computed = mavlink_x25_crc(
            packet[1 : payload_offset + payload_length],
            MAVLINK_GLOBAL_POSITION_INT_CRC_EXTRA,
        )
        if received != computed:
            return None
    else:
        return None

    payload = packet[payload_offset : payload_offset + payload_length]
    _, latitude_e7, longitude_e7, altitude_mm, _, _, _, _, _ = struct.unpack_from(
        "<IiiiihhhH", payload, 0
    )
    latitude = latitude_e7 * 1e-7
    longitude = longitude_e7 * 1e-7
    altitude_m = altitude_mm * 1e-3

    if not math.isfinite(latitude) or not math.isfinite(longitude):
        return None
    if latitude == 0.0 and longitude == 0.0:
        return None
    if abs(latitude) > 90.0 or abs(longitude) > 180.0:
        return None
    return latitude, longitude, altitude_m if math.isfinite(altitude_m) else 0.0


class MavlinkGpsRtcmOutput:
    """Optional hardware-compatible GPS_RTCM_DATA output."""

    def __init__(self, config: RoverConfig, runtime: RoverRuntime) -> None:
        self.config = config
        self.runtime = runtime
        self._udp_socket: socket.socket | None = None
        self._serial_fd: int | None = None
        self._packet_sequence = 0
        self._rtcm_sequence = 0
        self._rx_parser = MavlinkStreamParser()
        self._lock = threading.Lock()

    def start(self) -> None:
        mode = self.config.mavlink_output
        if mode == "none":
            return
        if mode == "udp":
            udp = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
            udp.connect((self.config.mavlink_udp_host, self.config.mavlink_udp_port))
            udp.setblocking(False)
            self._udp_socket = udp
            return
        if mode == "serial":
            self._serial_fd = self._open_serial(
                self.config.mavlink_serial_device,
                self.config.mavlink_serial_baud,
            )
            return
        raise ValueError(f"Unsupported MAVLink output mode: {mode}")

    def close(self) -> None:
        if self._udp_socket is not None:
            self._udp_socket.close()
            self._udp_socket = None
        if self._serial_fd is not None:
            os.close(self._serial_fd)
            self._serial_fd = None

    def _open_serial(self, device: str, baud: int) -> int:
        baud_constants = {
            9600: termios.B9600,
            19200: termios.B19200,
            38400: termios.B38400,
            57600: termios.B57600,
            115200: termios.B115200,
            230400: getattr(termios, "B230400", None),
            460800: getattr(termios, "B460800", None),
            500000: getattr(termios, "B500000", None),
            576000: getattr(termios, "B576000", None),
            921600: getattr(termios, "B921600", None),
            1000000: getattr(termios, "B1000000", None),
            1152000: getattr(termios, "B1152000", None),
            1500000: getattr(termios, "B1500000", None),
            2000000: getattr(termios, "B2000000", None),
        }
        speed = baud_constants.get(baud)
        if speed is None:
            raise ValueError(f"Unsupported serial baud: {baud}")

        fd = os.open(device, os.O_RDWR | os.O_NOCTTY | os.O_NONBLOCK)
        attrs = termios.tcgetattr(fd)
        attrs[0] = 0
        attrs[1] = 0
        attrs[2] = termios.CS8 | termios.CREAD | termios.CLOCAL
        attrs[3] = 0
        attrs[4] = speed
        attrs[5] = speed
        termios.tcsetattr(fd, termios.TCSANOW, attrs)
        return fd

    def _write(self, packet: bytes) -> bool:
        try:
            if self._udp_socket is not None:
                self._udp_socket.send(packet)
                return True
            if self._serial_fd is not None:
                view = memoryview(packet)
                while view:
                    try:
                        written = os.write(self._serial_fd, view)
                    except BlockingIOError:
                        time.sleep(0.01)
                        continue
                    view = view[written:]
                return True
            return self.config.mavlink_output == "none"
        except OSError:
            return False

    def poll_position(self) -> tuple[float, float, float] | None:
        """Read the latest PX4 GLOBAL_POSITION_INT from the MAVLink link."""
        chunks: list[bytes] = []

        if self._udp_socket is not None:
            while True:
                try:
                    chunks.append(self._udp_socket.recv(4096))
                except BlockingIOError:
                    break
                except OSError:
                    break

        if self._serial_fd is not None:
            while True:
                try:
                    chunk = os.read(self._serial_fd, 4096)
                except BlockingIOError:
                    break
                except OSError:
                    break
                if not chunk:
                    break
                chunks.append(chunk)

        latest: tuple[float, float, float] | None = None
        for chunk in chunks:
            for packet in self._rx_parser.feed(chunk):
                position = decode_global_position_int(packet)
                if position is not None:
                    latest = position
        return latest

    def send_rtcm(self, frame: bytes) -> None:
        data = frame[:MAVLINK_GPS_RTCM_DATA_MAX_LOGICAL]
        with self._lock:
            logical_sequence = self._rtcm_sequence & 0x1F
            self._rtcm_sequence = (self._rtcm_sequence + 1) & 0xFF

            chunks: list[tuple[int, bytes]] = []
            if len(data) < MAVLINK_GPS_RTCM_DATA_MAX_FIELD:
                chunks.append(((logical_sequence & 0x1F) << 3, data))
            else:
                for fragment_id, offset in enumerate(
                    range(0, len(data), MAVLINK_GPS_RTCM_DATA_MAX_FIELD)
                ):
                    flags = (
                        0x01
                        | ((fragment_id & 0x03) << 1)
                        | ((logical_sequence & 0x1F) << 3)
                    )
                    chunks.append(
                        (flags, data[offset : offset + MAVLINK_GPS_RTCM_DATA_MAX_FIELD])
                    )

            for flags, chunk in chunks:
                payload = (
                    bytes((flags, len(chunk)))
                    + chunk
                    + bytes(MAVLINK_GPS_RTCM_DATA_MAX_FIELD - len(chunk))
                )
                packet = build_mavlink2_packet(
                    payload=payload,
                    message_id=MAVLINK_MSG_ID_GPS_RTCM_DATA,
                    packet_sequence=self._packet_sequence,
                    system_id=self.config.mavlink_sysid,
                    component_id=self.config.mavlink_compid,
                    crc_extra=MAVLINK_GPS_RTCM_DATA_CRC_EXTRA,
                )
                self._packet_sequence = (self._packet_sequence + 1) & 0xFF
                write_ok = self._write(packet)
                self.runtime.record_mavlink(len(packet), write_ok)


class NtripRoverWorker(threading.Thread):
    """Emulate the deployed Raspberry Pi NTRIP -> MAVLink bridge."""

    def __init__(
        self,
        runtime: RoverRuntime,
        timeout_s: float,
        stop_event: threading.Event,
        start_delay_s: float,
        gga_interval_s: float,
        debug: bool,
    ) -> None:
        super().__init__(name=f"ROVER-{runtime.config.name}", daemon=True)
        self.runtime = runtime
        self.timeout_s = timeout_s
        self.stop_event = stop_event
        self.start_delay_s = start_delay_s
        self.gga_interval_s = gga_interval_s
        self.debug = debug
        self._stream_was_connected = False
        self._next_gga_at = time.monotonic()
        self._mavlink = MavlinkGpsRtcmOutput(runtime.config, runtime)
        self._vehicle_position: tuple[float, float, float] | None = None

    def run(self) -> None:
        if self.stop_event.wait(self.start_delay_s):
            return

        try:
            self._mavlink.start()
        except (OSError, ValueError) as error:
            self.runtime.set_status("error", connected=False, error=str(error))
            print(f"[{self.runtime.config.name}] MAVLINK ERROR: {error}", file=sys.stderr)
            return

        attempts = 0
        try:
            while not self.stop_event.is_set():
                self._stream_was_connected = False
                try:
                    self.runtime.set_status("connecting", connected=False)
                    self._run_connection()
                except (ConnectionError, OSError, TimeoutError) as error:
                    self.runtime.set_status("error", connected=False, error=str(error))
                    self.runtime.record_reconnect()
                    print(
                        f"[{self.runtime.config.name}] ROVER ERROR: {error}",
                        file=sys.stderr,
                    )

                if self.stop_event.is_set():
                    break

                if self._stream_was_connected:
                    attempts = 0

                backoff_s = min(16, 1 << min(attempts, 4))
                attempts += 1
                self.runtime.set_status("reconnecting", connected=False)
                if self.debug:
                    print(
                        f"[{self.runtime.config.name}] reconnect in {backoff_s}s "
                        f"(attempt {attempts})"
                    )
                self.stop_event.wait(backoff_s)
        finally:
            self.runtime.set_status("disconnected", connected=False)
            self._mavlink.close()

    def _run_connection(self) -> None:
        config = self.runtime.config
        if config.use_tls:
            raise ConnectionError("TLS is not implemented by the deployed C++ client.")

        with socket.create_connection(
            (config.ntrip_host, config.ntrip_port), timeout=self.timeout_s
        ) as stream:
            stream.setsockopt(socket.SOL_SOCKET, socket.SO_KEEPALIVE, 1)
            stream.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
            stream.settimeout(self.timeout_s)

            request = build_pi_bridge_handshake(config)
            if self.debug:
                printable = request.decode("ascii").replace(
                    f"Authorization: Basic {base64.b64encode(f'{config.username}:{config.password}'.encode()).decode()}",
                    "Authorization: Basic <redacted>",
                )
                print(f"[{config.name}] TX handshake:\n{printable.rstrip()}")
            stream.sendall(request)

            remaining = self._read_http_response(stream)
            parser = RtcmReceiveParser()
            self.runtime.set_status("connected", connected=True)
            self._stream_was_connected = True

            if remaining:
                self._consume_rtcm(parser, remaining)

            stream.settimeout(0.5)
            while not self.stop_event.is_set():
                now = time.monotonic()
                mavlink_position = self._mavlink.poll_position()
                if mavlink_position is not None:
                    self._vehicle_position = mavlink_position
                if now >= self._next_gga_at:
                    self._send_gga_if_available(stream)
                    while self._next_gga_at <= now:
                        self._next_gga_at += self.gga_interval_s

                try:
                    data = stream.recv(4096)
                except socket.timeout:
                    continue

                if not data:
                    raise ConnectionError("server closed the RTCM stream")
                self._consume_rtcm(parser, data)

    def _read_http_response(self, stream: socket.socket) -> bytes:
        response = bytearray()
        deadline = time.monotonic() + 10.0

        while not self.stop_event.is_set():
            if time.monotonic() > deadline:
                raise TimeoutError("HTTP response timeout")
            try:
                chunk = stream.recv(512)
            except socket.timeout:
                continue
            if not chunk:
                raise ConnectionError("peer closed during HTTP handshake")
            response.extend(chunk)
            if len(response) > 16 * 1024:
                raise ConnectionError("HTTP response header too large")

            separator_index = response.find(b"\r\n\r\n")
            if separator_index < 0:
                continue

            header = bytes(response[:separator_index])
            remaining = bytes(response[separator_index + 4 :])
            status_line = header.split(b"\r\n", 1)[0].decode(
                "ascii", errors="replace"
            )
            parts = status_line.split()
            try:
                code = int(parts[1])
            except (IndexError, ValueError) as error:
                raise ConnectionError(f"invalid HTTP response: {status_line}") from error

            if 200 <= code < 300:
                if self.debug:
                    print(
                        f"[{self.runtime.config.name}] RX {status_line}; "
                        f"trailing={len(remaining)} bytes"
                    )
                return remaining
            if code == 401:
                raise ConnectionError("HTTP 401 unauthorized (check user/password)")
            if code == 404:
                raise ConnectionError("HTTP 404 not found (check mountpoint)")
            if code == 429:
                raise ConnectionError("HTTP 429 connection limit reached")
            raise ConnectionError(f"HTTP {code}: {status_line}")

        raise ConnectionError("stopped during HTTP handshake")

    def _send_gga_if_available(self, stream: socket.socket) -> None:
        config = self.runtime.config
        position = self._vehicle_position
        if position is None:
            if config.fixed_latitude is None or config.fixed_longitude is None:
                return
            position = (
                config.fixed_latitude,
                config.fixed_longitude,
                config.fixed_altitude_m,
            )
        sentence = build_pi_bridge_gga(*position)
        stream.sendall(sentence)
        self.runtime.record_gga()
        if self.debug:
            print(f"[{config.name}] GGA {sentence.decode('ascii').strip()}")

    def _consume_rtcm(self, parser: RtcmReceiveParser, data: bytes) -> None:
        self.runtime.record_bytes(len(data))
        frames, crc_errors = parser.feed(data)
        self.runtime.record_crc_errors(crc_errors)

        whitelist = self.runtime.config.rtcm_whitelist
        for frame in frames:
            message_id = rtcm_message_type(frame)
            forwarded = not whitelist or message_id in whitelist
            self.runtime.record_frame(frame, forwarded)
            if forwarded:
                self._mavlink.send_rtcm(frame)
            elif self.debug:
                print(
                    f"[{self.runtime.config.name}] drop RTCM {message_id} "
                    "(not in whitelist)"
                )


class NtripSourceWorker(threading.Thread):
    """Maintain one NTRIP source connection and stream RTCM frames."""

    def __init__(
        self,
        runtime: StationRuntime,
        caster_host: str,
        caster_port: int,
        timeout_s: float,
        stop_event: threading.Event,
        real_frames: list[bytes] | None,
        replay_delay_s: float,
    ) -> None:
        super().__init__(
            name=f"NTRIP-{runtime.config.device_id}",
            daemon=True,
        )
        self.runtime = runtime
        self.caster_host = caster_host
        self.caster_port = caster_port
        self.timeout_s = timeout_s
        self.stop_event = stop_event
        self.real_frames = real_frames
        self.replay_delay_s = replay_delay_s
        self._sequence = 0

    def run(self) -> None:
        while not self.stop_event.is_set():
            try:
                self._run_connection()
            except (ConnectionError, OSError, TimeoutError) as error:
                self.runtime.set_connected(False)
                self.runtime.record_reconnect()
                print(
                    f"[{self.runtime.config.device_id}] "
                    f"NTRIP ERROR: {error}",
                    file=sys.stderr,
                )
                self.stop_event.wait(1.0)

        self.runtime.set_connected(False)

    def _run_connection(self) -> None:
        config = self.runtime.config

        with socket.create_connection(
            (self.caster_host, self.caster_port),
            timeout=self.timeout_s,
        ) as stream:
            stream.settimeout(self.timeout_s)
            mountpoint = quote(config.mountpoint, safe="-_.~")

            request = (
                f"POST /{mountpoint} HTTP/1.1\r\n"
                f"Host: {self.caster_host}:{self.caster_port}\r\n"
                "User-Agent: ESP32-NTRIP-Simulator/2.1\r\n"
                "Ntrip-Version: Ntrip/2.0\r\n"
                f"Authorization: Bearer {config.token}\r\n"
                "Content-Type: gnss/data\r\n"
                "Connection: keep-alive\r\n"
                "\r\n"
            ).encode("ascii")

            stream.sendall(request)
            response = self._read_headers(stream)
            status_line = response.splitlines()[0].decode(
                "ascii",
                errors="replace",
            )

            if "200" not in status_line:
                raise ConnectionError(
                    f"{config.device_id}: NTRIP source rejected: {status_line}"
                )

            stream.settimeout(None)
            self.runtime.set_connected(True)

            if self.real_frames:
                self._stream_real_frames(stream)
            else:
                self._stream_synthetic_frames(stream)

    def _read_headers(self, stream: socket.socket) -> bytes:
        response = bytearray()

        while len(response) < 8192:
            chunk = stream.recv(1024)

            if not chunk:
                raise ConnectionError("Caster closed during handshake.")

            response.extend(chunk)

            if b"\r\n\r\n" in response or b"\n\n" in response:
                return bytes(response)

        raise ConnectionError("Caster response headers are too large.")

    def _stream_real_frames(self, stream: socket.socket) -> None:
        assert self.real_frames is not None
        index = 0

        while not self.stop_event.is_set():
            frame = self.real_frames[index]
            stream.sendall(frame)
            self.runtime.record_frame(frame)

            index = (index + 1) % len(self.real_frames)
            self.stop_event.wait(self.replay_delay_s)

    def _stream_synthetic_frames(self, stream: socket.socket) -> None:
        config = self.runtime.config
        now = time.monotonic()
        next_due = {
            message_type: now
            for message_type in RTCM_PERIODS_S
        }

        while not self.stop_event.is_set():
            now = time.monotonic()
            sent_any = False

            for message_type, period_s in RTCM_PERIODS_S.items():
                if now < next_due[message_type]:
                    continue

                if message_type == 1005:
                    frame = build_type_1005(
                        station_id=config.station_id,
                        latitude=config.latitude,
                        longitude=config.longitude,
                        altitude_m=config.altitude_m,
                    )
                else:
                    frame = build_synthetic_rtcm_frame(
                        message_type=message_type,
                        station_id=config.station_id,
                        sequence=self._sequence,
                    )

                stream.sendall(frame)
                self.runtime.record_frame(frame)

                self._sequence += 1
                next_due[message_type] += period_s

                while next_due[message_type] <= now:
                    next_due[message_type] += period_s

                sent_any = True

            self.stop_event.wait(0.01 if sent_any else 0.03)


class TelemetrySender:
    def __init__(
        self,
        base_url: str,
        timeout_s: float,
        insecure: bool,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.timeout_s = timeout_s
        self.ssl_context = None

        if insecure:
            self.ssl_context = ssl._create_unverified_context()

    def send(
        self,
        runtime: StationRuntime,
        payload: dict[str, Any],
    ) -> tuple[int, str]:
        config = runtime.config
        url = (
            f"{self.base_url}/api/v1/stations/"
            f"{quote(config.device_id, safe='-_.~')}/telemetry"
        )
        body = json.dumps(
            payload,
            separators=(",", ":"),
        ).encode("utf-8")

        request = urllib.request.Request(
            url=url,
            data=body,
            method="POST",
            headers={
                "Accept": "application/json",
                "Content-Type": "application/json",
                "X-Station-Token": config.token,
                "User-Agent": "ESP32-NTRIP-Simulator/2.1",
            },
        )

        try:
            with urllib.request.urlopen(
                request,
                timeout=self.timeout_s,
                context=self.ssl_context,
            ) as response:
                response_body = response.read().decode(
                    "utf-8",
                    errors="replace",
                )
                return response.status, response_body
        except urllib.error.HTTPError as error:
            return (
                error.code,
                error.read().decode("utf-8", errors="replace"),
            )
        except (urllib.error.URLError, TimeoutError) as error:
            return 0, str(error)


