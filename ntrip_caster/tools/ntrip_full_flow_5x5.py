def run_self_test() -> int:
    test_config = StationConfig(**DEFAULT_STATIONS[0])
    frames = [
        build_type_1005(
            test_config.station_id,
            test_config.latitude,
            test_config.longitude,
            test_config.altitude_m,
        )
    ]
    frames.extend(
        build_synthetic_rtcm_frame(
            message_type=message_type,
            station_id=test_config.station_id,
            sequence=index,
        )
        for index, message_type in enumerate((1074, 1084, 1094, 1124, 1230))
    )
    if not all(validate_rtcm_frame(frame) for frame in frames):
        print("ERROR: generated RTCM frame failed CRC validation.")
        return 1

    rover = RoverConfig(
        name="SELFTEST",
        ntrip_host="127.0.0.1",
        ntrip_port=2101,
        mountpoint="BASE",
        username="huy",
        password="123456",
        fixed_latitude=10.9801234,
        fixed_longitude=106.6745678,
        fixed_altitude_m=18.4,
    )
    expected_request = (
        "GET /BASE HTTP/1.0\r\n"
        "Host: 127.0.0.1\r\n"
        "Ntrip-Version: Ntrip/2.0\r\n"
        "User-Agent: NTRIP PiNtripBridge/1.0\r\n"
        "Authorization: Basic aHV5OjEyMzQ1Ng==\r\n\r\n"
    ).encode("ascii")
    if build_pi_bridge_handshake(rover) != expected_request:
        print("ERROR: Pi bridge HTTP handshake does not match ntrip.cc.")
        return 1

    fixed_time = time.struct_time((2026, 7, 17, 1, 2, 3, 0, 0, 0))
    gga = build_pi_bridge_gga(
        10.9801234, 106.6745678, 18.4, utc_time=fixed_time
    )
    if not gga.startswith(b"$GPGGA,010203,") or not gga.endswith(b"\r\n"):
        print("ERROR: GGA format does not match ntrip.cc.")
        return 1
    body, transmitted_checksum = gga[1:].strip().rsplit(b"*", 1)
    checksum = 0
    for byte in body:
        checksum ^= byte
    if transmitted_checksum != f"{checksum:02X}".encode("ascii"):
        print("ERROR: GGA checksum is invalid.")
        return 1

    runtime = RoverRuntime(rover)
    output = MavlinkGpsRtcmOutput(rover, runtime)
    # Exercise the exact fragmentation rules without opening an output device.
    short_payload = (
        bytes((0, len(frames[0])))
        + frames[0]
        + bytes(MAVLINK_GPS_RTCM_DATA_MAX_FIELD - len(frames[0]))
    )
    packet = build_mavlink2_packet(
        payload=short_payload,
        message_id=MAVLINK_MSG_ID_GPS_RTCM_DATA,
        packet_sequence=0,
        system_id=255,
        component_id=190,
        crc_extra=MAVLINK_GPS_RTCM_DATA_CRC_EXTRA,
    )
    if not validate_mavlink2_packet(packet, MAVLINK_GPS_RTCM_DATA_CRC_EXTRA):
        print("ERROR: MAVLink GPS_RTCM_DATA packet CRC is invalid.")
        return 1
    if len(packet) != 194:
        print(f"ERROR: unexpected MAVLink packet length: {len(packet)}")
        return 1

    global_position_payload = struct.pack(
        "<IiiiihhhH",
        1234,
        round(10.9801234 * 1e7),
        round(106.6745678 * 1e7),
        18400,
        1000,
        0,
        0,
        0,
        0,
    )
    global_position_packet = build_mavlink2_packet(
        payload=global_position_payload,
        message_id=MAVLINK_MSG_ID_GLOBAL_POSITION_INT,
        packet_sequence=1,
        system_id=1,
        component_id=1,
        crc_extra=MAVLINK_GLOBAL_POSITION_INT_CRC_EXTRA,
    )
    decoded_position = decode_global_position_int(global_position_packet)
    if decoded_position is None:
        print("ERROR: GLOBAL_POSITION_INT decoding failed.")
        return 1
    if abs(decoded_position[0] - 10.9801234) > 1e-7:
        print("ERROR: decoded MAVLink latitude is incorrect.")
        return 1
    del output

    print(
        "Hardware simulator self-test OK:\n"
        "  RTCM CRC:      1005, 1074, 1084, 1094, 1124, 1230\n"
        "  NTRIP client:  HTTP/1.0 + Basic auth + PiNtripBridge user-agent\n"
        "  GGA:           exact ntrip.cc shape and checksum\n"
        "  MAVLink:       GPS_RTCM_DATA output + GLOBAL_POSITION_INT input OK"
    )
    return 0


def main() -> int:
    args = parse_args()

    if args.self_test:
        return run_self_test()

    if args.interval <= 0 or args.timeout <= 0:
        print("ERROR: --interval and --timeout must be greater than 0.", file=sys.stderr)
        return 2
    if not 1 <= args.caster_port <= 65535:
        print("ERROR: --caster-port is invalid.", file=sys.stderr)
        return 2
    if args.replay_delay_ms <= 0:
        print("ERROR: --replay-delay-ms must be greater than 0.", file=sys.stderr)
        return 2
    if args.rovers_per_station < 0 or args.ntrip_client_count < 0:
        print("ERROR: rover counts cannot be negative.", file=sys.stderr)
        return 2
    if args.rover_start_delay < 0 or args.rover_gga_interval <= 0:
        print("ERROR: invalid rover timing.", file=sys.stderr)
        return 2
    if args.mavlink_output == "config" and args.ntrip_client_config is None:
        print(
            "ERROR: --mavlink-output=config requires --ntrip-client-config.",
            file=sys.stderr,
        )
        return 2

    try:
        rover_whitelist = parse_rtcm_whitelist(args.rover_rtcm_whitelist)
    except ValueError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2

    selected_ids = set(args.only)
    selected = [
        StationConfig(**item)
        for item in DEFAULT_STATIONS
        if not selected_ids or item["device_id"] in selected_ids
    ]
    if not selected:
        print("ERROR: No matching station profile.", file=sys.stderr)
        return 2

    real_frames = None
    if args.rtcm_file is not None:
        try:
            real_frames = load_rtcm_file(args.rtcm_file)
        except (OSError, ValueError) as error:
            print(f"ERROR: {error}", file=sys.stderr)
            return 2
        counts = Counter(rtcm_message_type(frame) for frame in real_frames)
        print(
            f"Loaded {len(real_frames)} valid RTCM frames: "
            + ", ".join(
                f"{message_type}={count}"
                for message_type, count in sorted(counts.items())
            )
        )

    rover_configs: list[RoverConfig] = []

    for station in selected:
        for rover_index in range(args.rovers_per_station):
            rover_configs.append(
                RoverConfig(
                    name=f"PI-{station.station_id:03d}-{rover_index + 1:02d}",
                    ntrip_host=args.caster_host,
                    ntrip_port=args.caster_port,
                    mountpoint=station.mountpoint,
                    username=args.rover_username,
                    password=args.rover_password,
                    fixed_latitude=station.latitude + (rover_index + 1) * 0.00001,
                    fixed_longitude=station.longitude + (rover_index + 1) * 0.00001,
                    fixed_altitude_m=station.altitude_m,
                    rtcm_whitelist=rover_whitelist,
                    mavlink_output=(
                        args.mavlink_output
                        if args.mavlink_output in {"none", "udp", "serial"}
                        else "none"
                    ),
                    mavlink_udp_host=args.mavlink_udp_host,
                    mavlink_udp_port=args.mavlink_udp_port,
                    mavlink_serial_device=args.mavlink_serial_device,
                    mavlink_serial_baud=args.mavlink_serial_baud,
                    mavlink_sysid=args.mavlink_sysid,
                    mavlink_compid=args.mavlink_compid,
                )
            )

    if args.ntrip_client_config is not None:
        try:
            for client_index in range(args.ntrip_client_count):
                rover_configs.append(
                    load_pi_bridge_config(
                        args.ntrip_client_config,
                        name=f"PI-CONFIG-{client_index + 1:02d}",
                        mavlink_output_override=args.mavlink_output,
                        udp_host_override=args.mavlink_udp_host,
                        udp_port_override=args.mavlink_udp_port,
                        serial_device_override=args.mavlink_serial_device,
                        serial_baud_override=args.mavlink_serial_baud,
                        sysid_override=args.mavlink_sysid,
                        compid_override=args.mavlink_compid,
                    )
                )
        except (OSError, ValueError) as error:
            print(f"ERROR: cannot load NTRIP client config: {error}", file=sys.stderr)
            return 2

    if args.rover_only and not rover_configs:
        print(
            "ERROR: --rover-only requires --rovers-per-station > 0 or "
            "--ntrip-client-config.",
            file=sys.stderr,
        )
        return 2

    serial_rovers = [
        config for config in rover_configs if config.mavlink_output == "serial"
    ]
    if len(serial_rovers) > 1:
        print(
            "ERROR: multiple rover instances cannot safely write the same serial "
            "MAVLink device. Use one client or UDP output.",
            file=sys.stderr,
        )
        return 2

    stop_event = threading.Event()
    station_runtimes = [StationRuntime(config=item) for item in selected]
    rover_runtimes = [RoverRuntime(config=item) for item in rover_configs]
    source_workers: list[NtripSourceWorker] = []
    rover_workers: list[NtripRoverWorker] = []

    def stop_handler(_signal_number: int, _frame: Any) -> None:
        stop_event.set()

    signal.signal(signal.SIGINT, stop_handler)
    signal.signal(signal.SIGTERM, stop_handler)

    if not args.rover_only and not args.no_rtcm:
        source_workers = [
            NtripSourceWorker(
                runtime=runtime,
                caster_host=args.caster_host,
                caster_port=args.caster_port,
                timeout_s=args.timeout,
                stop_event=stop_event,
                real_frames=real_frames,
                replay_delay_s=args.replay_delay_ms / 1000.0,
            )
            for runtime in station_runtimes
        ]
        for worker in source_workers:
            worker.start()

    rover_workers = [
        NtripRoverWorker(
            runtime=runtime,
            timeout_s=args.timeout,
            stop_event=stop_event,
            start_delay_s=args.rover_start_delay,
            gga_interval_s=args.rover_gga_interval,
            debug=args.debug_rover,
        )
        for runtime in rover_runtimes
    ]
    for worker in rover_workers:
        worker.start()

    sender = TelemetrySender(
        base_url=args.base_url,
        timeout_s=args.timeout,
        insecure=args.insecure,
    )

    print("=" * 72)
    print("CTUAV NTRIP FULL-FLOW SIMULATOR")
    print(
        f"Preset: {len(station_runtimes)} base stations + "
        f"{len(rover_runtimes)} rover clients"
    )
    print(
        f"Expected live NTRIP sessions after connection: "
        f"{len(source_workers) + len(rover_workers)}"
    )
    print("=" * 72)
    print(f"HTTP telemetry: {args.base_url}")
    print(f"NTRIP Source:   {args.caster_host}:{args.caster_port}")
    print(
        "Stations:       "
        + (
            ", ".join(runtime.config.device_id for runtime in station_runtimes)
            if not args.rover_only
            else "disabled"
        )
    )
    print(f"Rover clients:  {len(rover_runtimes)}")
    for runtime in rover_runtimes:
        config = runtime.config
        auth = config.username if config.username else "anonymous"
        if config.mavlink_output != "none":
            gga = (
                "MAVLink position, then fixed fallback"
                if config.fixed_latitude is not None and config.fixed_longitude is not None
                else "MAVLink vehicle position"
            )
        else:
            gga = (
                "fixed fallback"
                if config.fixed_latitude is not None and config.fixed_longitude is not None
                else "disabled (no MAVLink position or fixed fallback)"
            )
        whitelist = (
            ",".join(str(item) for item in sorted(config.rtcm_whitelist))
            if config.rtcm_whitelist
            else "all"
        )
        print(
            f"  [{config.name}] {config.ntrip_host}:{config.ntrip_port}/"
            f"{config.mountpoint} auth={auth} gga={gga} "
            f"rtcm={whitelist} mavlink={config.mavlink_output}"
        )

    if args.once and (source_workers or rover_workers):
        stop_event.wait(max(1.25, args.rover_start_delay + 1.25))

    try:
        while not stop_event.is_set():
            cycle_started = time.monotonic()

            if not args.rover_only:
                for runtime in station_runtimes:
                    payload = runtime.snapshot(
                        caster_host=args.caster_host,
                        caster_port=args.caster_port,
                        management_url=args.base_url,
                    )
                    status, response_body = sender.send(runtime, payload)
                    rtcm = payload["rtcm"]
                    state = "UP" if rtcm["connected"] else "DOWN"
                    if 200 <= status < 300:
                        print(
                            f"[{runtime.config.device_id}] HTTP={status} "
                            f"SOURCE={state} RTCM={rtcm['upload_bps']}bps "
                            f"frames={rtcm['frames_valid']} crc={rtcm['crc_errors']}"
                        )
                    else:
                        message = response_body.strip().replace("\n", " ")
                        print(
                            f"[{runtime.config.device_id}] HTTP ERROR {status}: {message}",
                            file=sys.stderr,
                        )

            for runtime in rover_runtimes:
                rover = runtime.snapshot()
                age = f"{rover['age_ms']}ms" if rover["age_ms"] is not None else "-"
                error = f" error={rover['last_error']}" if rover["last_error"] else ""
                print(
                    f"[{rover['name']}] status={rover['status']} "
                    f"mount={rover['mountpoint']} RTCM={rover['download_bps']}bps "
                    f"frames={rover['frames_valid']} crc={rover['crc_errors']} "
                    f"forwarded={rover['frames_forwarded']} "
                    f"mavpkt={rover['mavlink_packets_sent']} gga={rover['gga_sent']} "
                    f"age={age}{error}"
                )

            if args.once:
                break

            elapsed = time.monotonic() - cycle_started
            stop_event.wait(max(0.0, args.interval - elapsed))
    finally:
        stop_event.set()
        for worker in source_workers:
            worker.join(timeout=args.timeout + 17.0)
        for worker in rover_workers:
            worker.join(timeout=args.timeout + 17.0)

    print("Simulator stopped.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
