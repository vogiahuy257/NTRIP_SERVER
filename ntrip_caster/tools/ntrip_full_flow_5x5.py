def crc24q(data: bytes) -> int:
    """Calculate the RTCM3 CRC24Q checksum."""
    crc = 0

    for byte in data:
        crc ^= byte << 16

        for _ in range(8):
            crc <<= 1

            if crc & 0x1000000:
                crc ^= CRC24Q_POLYNOMIAL

    return crc & 0xFFFFFF


def rtcm_message_type(frame: bytes) -> int:
    """Return the 12-bit RTCM message number."""
    if len(frame) < 8 or frame[0] != 0xD3:
        return -1

    return (frame[3] << 4) | (frame[4] >> 4)


def build_rtcm_frame(payload: bytes) -> bytes:
    """Wrap a payload in an RTCM3 transport frame with CRC24Q."""
    payload_length = len(payload)

    if payload_length > 1023:
        raise ValueError("RTCM payload exceeds 1023 bytes.")

    header = bytes(
        (
            0xD3,
            (payload_length >> 8) & 0x03,
            payload_length & 0xFF,
        )
    )
    body = header + payload
    checksum = crc24q(body).to_bytes(3, "big")

    return body + checksum


class BitWriter:
    """Minimal MSB-first bit writer for RTCM payload construction."""

    def __init__(self) -> None:
        self._bits: list[int] = []

    def unsigned(self, value: int, width: int) -> None:
        if value < 0 or value >= (1 << width):
            raise ValueError(f"{value} does not fit in {width} unsigned bits.")

        for shift in range(width - 1, -1, -1):
            self._bits.append((value >> shift) & 1)

    def signed(self, value: int, width: int) -> None:
        minimum = -(1 << (width - 1))
        maximum = (1 << (width - 1)) - 1

        if not minimum <= value <= maximum:
            raise ValueError(f"{value} does not fit in {width} signed bits.")

        self.unsigned(value & ((1 << width) - 1), width)

    def to_bytes(self) -> bytes:
        while len(self._bits) % 8:
            self._bits.append(0)

        output = bytearray()

        for offset in range(0, len(self._bits), 8):
            value = 0

            for bit in self._bits[offset : offset + 8]:
                value = (value << 1) | bit

            output.append(value)

        return bytes(output)


def geodetic_to_ecef(
    latitude_deg: float,
    longitude_deg: float,
    altitude_m: float,
) -> tuple[float, float, float]:
    """Convert WGS84 latitude, longitude and altitude to ECEF metres."""
    semi_major_axis = 6378137.0
    inverse_flattening = 298.257223563
    flattening = 1.0 / inverse_flattening
    eccentricity_sq = flattening * (2.0 - flattening)

    latitude = math.radians(latitude_deg)
    longitude = math.radians(longitude_deg)

    sin_latitude = math.sin(latitude)
    cos_latitude = math.cos(latitude)
    prime_vertical = semi_major_axis / math.sqrt(
        1.0 - eccentricity_sq * sin_latitude * sin_latitude
    )

    x = (prime_vertical + altitude_m) * cos_latitude * math.cos(longitude)
    y = (prime_vertical + altitude_m) * cos_latitude * math.sin(longitude)
    z = (
        prime_vertical * (1.0 - eccentricity_sq) + altitude_m
    ) * sin_latitude

    return x, y, z


def build_type_1005(
    station_id: int,
    latitude: float,
    longitude: float,
    altitude_m: float,
) -> bytes:
    """Build a valid RTCM type 1005 fixed reference-station position."""
    x, y, z = geodetic_to_ecef(latitude, longitude, altitude_m)
    writer = BitWriter()

    writer.unsigned(1005, 12)
    writer.unsigned(station_id, 12)
    writer.unsigned(0, 6)   # ITRF realization year.
    writer.unsigned(1, 1)   # GPS indicator.
    writer.unsigned(1, 1)   # GLONASS indicator.
    writer.unsigned(1, 1)   # Galileo indicator.
    writer.unsigned(0, 1)   # Physical reference station indicator.
    writer.signed(round(x / 0.0001), 38)
    writer.unsigned(1, 1)   # Single receiver oscillator indicator.
    writer.unsigned(0, 1)   # Reserved.
    writer.signed(round(y / 0.0001), 38)
    writer.unsigned(0, 2)   # Quarter cycle indicator.
    writer.signed(round(z / 0.0001), 38)

    return build_rtcm_frame(writer.to_bytes())


def build_synthetic_rtcm_frame(
    message_type: int,
    station_id: int,
    sequence: int,
) -> bytes:
    """Build a deterministic CRC-valid test frame for one RTCM message type."""
    payload_size = SYNTHETIC_PAYLOAD_BYTES[message_type]
    payload = bytearray(payload_size)

    # RTCM payload starts with a 12-bit message number followed by a
    # 12-bit reference-station ID for the message set used here.
    payload[0] = (message_type >> 4) & 0xFF
    payload[1] = ((message_type & 0x0F) << 4) | ((station_id >> 8) & 0x0F)
    payload[2] = station_id & 0xFF

    # Fill the remaining payload deterministically. This gives realistic frame
    # lengths and repeatable UI/network load while retaining a valid CRC.
    state = (
        (message_type * 1103515245)
        ^ (station_id * 12345)
        ^ (sequence * 2654435761)
    ) & 0xFFFFFFFF

    for index in range(3, payload_size):
        state = (1664525 * state + 1013904223) & 0xFFFFFFFF
        payload[index] = (state >> 24) & 0xFF

    return build_rtcm_frame(bytes(payload))


def validate_rtcm_frame(frame: bytes) -> bool:
    """Validate RTCM preamble, declared length and CRC."""
    if len(frame) < 6 or frame[0] != 0xD3:
        return False

    if frame[1] & 0xFC:
        return False

    payload_length = ((frame[1] & 0x03) << 8) | frame[2]
    expected_length = 3 + payload_length + 3

    if len(frame) != expected_length:
        return False

    expected_crc = int.from_bytes(frame[-3:], "big")
    return crc24q(frame[:-3]) == expected_crc


def load_rtcm_file(path: Path) -> list[bytes]:
    """Extract all CRC-valid RTCM3 frames from a binary capture."""
    data = path.read_bytes()
    frames: list[bytes] = []
    offset = 0

    while offset < len(data):
        start = data.find(b"\xD3", offset)

        if start < 0:
            break

        if start + 3 > len(data):
            break

        if data[start + 1] & 0xFC:
            offset = start + 1
            continue

        payload_length = ((data[start + 1] & 0x03) << 8) | data[start + 2]
        frame_length = 3 + payload_length + 3
        end = start + frame_length

        if end > len(data):
            break

        frame = data[start:end]

        if validate_rtcm_frame(frame):
            frames.append(frame)
            offset = end
        else:
            offset = start + 1

    if not frames:
        raise ValueError(f"No valid RTCM3 frame found in {path}.")

    return frames


